// Writes src/data/photoUrls.ts: one line per photo in src/assets/countries.
// Every photo is listed with its exact file name, so it is only downloaded when it is shown (fast on localhost, and correct in the online build).
// Run after adding or removing photos:  node scripts/build-photo-urls.mjs
import { readdirSync, writeFileSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = 'src/assets/countries'
const files = []
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) walk(full)
    else if (name.endsWith('.webp')) files.push(relative(root, full).replace(/\\/g, '/'))
  }
}
walk(root)
const lines = files.map((f) => `  '${f.replace(/\.webp$/, '')}': new URL('../assets/countries/${f}', import.meta.url).href,`)
writeFileSync(
  'src/data/photoUrls.ts',
  `// GENERATED by scripts/build-photo-urls.mjs. Do not edit by hand.\nexport const PHOTO_URLS: Record<string, string> = {\n${lines.join('\n')}\n}\n`,
)
console.log(files.length, 'photos listed')
